"""Join catalog, pixel metrics and vision labels into research/logos.csv and write research/patterns.md.

    python3 -I scripts/summarize.py          (from the repo root)

Groups compared in the tables:
  all        every labeled logo
  craft 4+   logos the labelers rated 4 or 5 for professional quality (the target)
  craft 1-2  logos rated 1 or 2 (what to avoid)
  YC         Y Combinator companies that reached Series A or later, went public, were acquired, or are YC top companies
"""
import colorsys, csv, glob, json, os, statistics as st
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "research")


def hsl(hexv):
    h = hexv.lstrip("#")
    r, g, b = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    H, L, S = colorsys.rgb_to_hls(r, g, b)
    return H * 360, S, L


def family(hexv):
    if not hexv or len(hexv.lstrip("#")) != 6:
        return ""
    h, s, l = hsl(hexv)
    if l < 0.14:
        return "black"
    if l > 0.93:
        return "white"
    if s < 0.16:
        return "gray"
    for lim, n in ((15, "red"), (40, "orange"), (66, "yellow"), (165, "green"), (195, "teal"), (250, "blue"), (290, "purple"), (335, "pink"), (361, "red")):
        if h < lim:
            return n


def brand_color(r):
    """The logo's main non neutral color: the official hex for simple-icons, else the largest saturated palette entry."""
    if r["source"] == "si":
        return r["hex"]
    best = None
    for part in (r["palette"] or "").split():
        hx, share = part.split(":")
        h, s, l = hsl(hx)
        if s >= 0.16 and 0.14 <= l <= 0.93:
            return hx
        best = best or hx
    return best or ""


def load():
    cat = {r["id"]: r for r in csv.DictReader(open(os.path.join(R, "catalog.csv")))}
    met = {r["id"]: r for r in csv.DictReader(open(os.path.join(R, "metrics.csv")))}
    lab = {}
    for f in sorted(glob.glob(os.path.join(R, "labels", "*.jsonl"))):
        for line in open(f):
            line = line.strip()
            if line:
                try:
                    o = json.loads(line)
                except ValueError:
                    continue
                lab[o.get("id")] = o
    rows = []
    for i, c in cat.items():
        m = met.get(i, {})
        l = lab.get(i, {})
        r = dict(c)
        r.update({k: v for k, v in m.items() if k not in r})
        for k in ("comp", "kind", "cont", "style", "simple", "craft", "type", "case", "weight", "track", "custom", "sym", "skip"):
            v = l.get(k)
            r["l_" + k] = "" if v is None else str(v)
        r["labeled"] = "1" if l and not l.get("skip") else ""
        r["brand_hex"] = brand_color(r) if not m.get("err") else ""
        r["brand_family"] = family(r["brand_hex"])
        rows.append(r)
    return rows


def share_table(groups, key, order=None, title=None, note=""):
    cols = list(groups)
    counts = {g: Counter(r[key] for r in rs if r[key] != "") for g, rs in groups.items()}
    vals = order or [v for v, _ in Counter().__class__(sum((counts[g] for g in cols), Counter())).most_common()]
    out = ["| %s | %s |" % (title or key, " | ".join("%s (n=%d)" % (g, sum(counts[g].values())) for g in cols)),
           "|---|" + "---|" * len(cols)]
    for v in vals:
        cells = []
        for g in cols:
            n = sum(counts[g].values())
            cells.append("%d%%" % round(100 * counts[g][v] / n) if n else "")
        out.append("| %s | %s |" % (v, " | ".join(cells)))
    return "\n".join(out) + ("\n\n" + note if note else "")


def q(vals, p):
    vals = sorted(vals)
    if not vals:
        return float("nan")
    return vals[min(len(vals) - 1, int(p * len(vals)))]


def main():
    rows = load()
    cols = ["id", "key", "brand", "source", "kind", "file", "url", "category", "basis", "brand_hex", "brand_family", "n_colors",
            "dominant_hex", "palette", "bbox_aspect", "coverage", "sym_lr", "sym_tb", "parts", "complexity", "svg_gradient",
            "lock_gap", "lock_text_h", "lock_text_mid", "labeled"] + ["l_" + k for k in ("comp", "kind", "cont", "style", "simple", "craft", "type", "case", "weight", "track", "custom", "sym")]
    with open(os.path.join(R, "logos.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)

    L = [r for r in rows if r["labeled"]]
    brands = {r["key"] for r in rows}
    marks = [r for r in L if r["kind"] != "wordmark"]
    words = [r for r in L if r["l_type"]]
    G = lambda rs: {"all": rs, "craft 4+": [r for r in rs if r["l_craft"] in ("4", "5")],
                    "craft 1-2": [r for r in rs if r["l_craft"] in ("1", "2")], "YC": [r for r in rs if r["source"] == "yc"]}
    src = Counter(r["source"] for r in rows)
    md = ["# Logo patterns", "",
          "Research behind the brand-creator skill, generated by `scripts/summarize.py`. Do not edit by hand.", "",
          "## Data", "",
          "%d logo files from %d unique brands. %d files were labeled by eye from contact sheets (see `labeling_guide.md`); every file was also measured from pixels (`scripts/analyze_logos.py`)." % (len(rows), len(brands), len(L)), "",
          "| source | files | what it is |", "|---|---|---|",
          "| simple-icons | %d | monochrome brand icons with each brand's official hex color |" % src["si"],
          "| gilbarbara/logos | %d | full color tech logos, many with both a symbol file and a full logo file |" % src["gb"],
          "| svgl | %d | modern tech and AI logos, with separate wordmark files |" % src["svgl"],
          "| YC | %d | YC companies that reached Series A or later, went public, were acquired, or are YC top companies (raster thumbnails) |" % src["yc"],
          "| Wikidata | %d | tech companies with a logo and 5 or more Wikipedia language editions (download stopped by Wikimedia rate limits) |" % src["wd"], "",
          "Labels are judgments by vision models, about plus or minus 5 points. The craft score is the labelers' rating of professional quality; it is how this research separates good from weak logos, so treat craft 4+ as the target and craft 1-2 as what to avoid. simple-icons glyphs are single color by construction, so their color counts are left out of color tables and only their official hex is used.", ""]

    md += ["## Symbols", "", "### What the mark is", "",
           share_table(G(marks), "l_kind", ["G", "LI", "LM", "P", "C", "R", "D", "N", "X"], "kind",
                       "G abstract geometric, LI letterform of the initial, LM monogram or other letter, P pictorial object, C character or animal, R lines bars or waves, D dots or grid, N negative space trick, X text only."), "",
           "### Composition", "", share_table(G(marks), "l_comp", ["S", "W", "SW", "B"], "comp", "S symbol only, W lettering only, SW symbol plus word, B badge."), "",
           "### Container", "", share_table(G(marks), "l_cont", ["none", "circle", "square", "rsquare", "shield", "hex", "other"], "container"), "",
           "### Drawing style", "", share_table(G(marks), "l_style", ["flat", "cut", "line", "detail"], "style", "flat solid fills, cut solid with knocked out parts, line outlines or strokes, detail illustrative, shaded, 3D or gradient."), "",
           "### Simplicity (1 = draw from memory, 5 = intricate)", "", share_table(G(marks), "l_simple", ["1", "2", "3", "4", "5"], "simple"), ""]

    # measured shape stats for icons
    def numstats(rs, k):
        v = [float(r[k]) for r in rs if r.get(k) not in ("", None)]
        return "median %.2f, middle half %.2f to %.2f" % (st.median(v), q(v, .25), q(v, .75)) if v else "n/a"
    md += ["### Measured shape", "", "| group | parts | edge complexity | left right symmetry | ink coverage of its box |", "|---|---|---|---|---|"]
    for g, rs in G([r for r in marks if r["source"] in ("si", "gb", "svgl")]).items():
        if rs:
            md.append("| %s (n=%d) | %s | %s | %s | %s |" % (g, len(rs), numstats(rs, "parts"), numstats(rs, "complexity"), numstats(rs, "sym_lr"), numstats(rs, "coverage")))
    sym_hi = lambda rs: round(100 * sum(float(r["sym_lr"] or 0) > 0.95 for r in rs) / max(1, len(rs)))
    gg = G([r for r in marks if r["source"] in ("si", "gb", "svgl")])
    md += ["", "Mirror symmetric left to right (over 95 percent of pixels match): all %d%%, craft 4+ %d%%, craft 1-2 %d%%. Parts are separate filled shapes; complexity is edge length relative to area (a plain circle is about 3.5)." % (
        sym_hi(gg["all"]), sym_hi(gg["craft 4+"]), sym_hi(gg["craft 1-2"])), ""]

    # colors
    colored = [r for r in L if r["source"] != "si"]
    md += ["## Color", "", "### Main brand color family", "",
           share_table({"official hex (simple-icons)": [r for r in rows if r["source"] == "si" and r["brand_family"]],
                        "craft 4+": [r for r in L if r["l_craft"] in ("4", "5") and r["brand_family"]],
                        "craft 1-2": [r for r in L if r["l_craft"] in ("1", "2") and r["brand_family"]],
                        "YC": [r for r in rows if r["source"] == "yc" and r["brand_family"]]},
                       "brand_family", ["blue", "black", "red", "green", "orange", "purple", "teal", "yellow", "gray", "pink", "white"], "family"), "",
           "### Number of colors in the logo (full color sources only)", "",
           share_table(G([r for r in colored if r["source"] in ("gb", "svgl")]), "n_colors", ["1", "2", "3", "4", "5", "6"], "colors",
                       "Counted from pixels: a color must cover at least 4 percent of the ink. Black text plus one brand color counts as 2."), ""]
    gradr = [r for r in rows if r["source"] in ("gb", "svgl") and r["svg_gradient"] != ""]
    gshare = lambda rs: round(100 * sum(r["svg_gradient"] == "1" for r in rs) / max(1, len(rs)))
    gG = G([r for r in gradr if r["labeled"]])
    md += ["SVG gradient used: all %d%%, craft 4+ %d%%, craft 1-2 %d%% (gilbarbara and svgl files)." % (gshare(gr := gradr), gshare(gG["craft 4+"]), gshare(gG["craft 1-2"])), ""]
    sat = [hsl(r["brand_hex"]) for r in L if r["l_craft"] in ("4", "5") and r["brand_family"] not in ("", "black", "white", "gray")]
    if sat:
        md += ["Saturation and lightness of the main color in craft 4+ logos: saturation median %.2f, lightness median %.2f (middle half %.2f to %.2f). Strong brands pick a saturated, mid lightness color rather than a pastel or a dark muddy one." % (
            st.median(s for _, s, _ in sat), st.median(l for _, _, l in sat), q([l for _, _, l in sat], .25), q([l for _, _, l in sat], .75)), ""]
    top_hex = Counter(r["brand_hex"].upper() for r in rows if r["source"] == "si" and r["brand_hex"]).most_common(12)
    md += ["Most common official hex values: " + ", ".join("%s (%d)" % (h, n) for h, n in top_hex) + ".", ""]

    # wordmarks
    WG = {"all": words, "craft 4+": [r for r in words if r["l_craft"] in ("4", "5")], "craft 1-2": [r for r in words if r["l_craft"] in ("1", "2")]}
    md += ["## Wordmarks", "", "From %d labeled wordmark and full logo files (svgl wordmarks and gilbarbara full logos)." % len(words), "",
           "### Typeface class", "", share_table(WG, "l_type", ["neo", "geo", "hum", "round", "display", "serif", "slab", "mono"], "type",
                                                 "neo neo grotesk (Helvetica, Inter), geo geometric sans, hum humanist sans, round rounded sans, display custom or stylized."), "",
           "### Case", "", share_table(WG, "l_case", ["lower", "title", "upper", "camel", "mixed"], "case"), "",
           "### Weight", "", share_table(WG, "l_weight", ["light", "regular", "medium", "bold", "black"], "weight"), "",
           "### Letter spacing", "", share_table(WG, "l_track", ["tight", "normal", "wide"], "tracking"), "",
           "### The one custom detail", "", share_table(WG, "l_custom", ["none", "letter", "lig", "color", "dot", "cut", "symbol"], "custom"), "",
           "### Symbol position", "", share_table(WG, "l_sym", ["left", "none", "top", "inside", "right"], "position"), ""]
    lk = [r for r in rows if r["lock_gap"]]
    if lk:
        gp = [float(r["lock_gap"]) for r in lk]
        th = [float(r["lock_text_h"]) for r in lk]
        tm = [float(r["lock_text_mid"]) for r in lk]
        md += ["### Lockup proportions (measured)", "",
               "In %d horizontal logos with a symbol on the left, measured in units of the symbol height: the gap between symbol and word has median %.2f (middle half %.2f to %.2f); the word's ink height has median %.2f (middle half %.2f to %.2f); the word's vertical center sits %.2f symbol heights from the symbol's center (median, positive is lower). The builder defaults (`cap_ratio` 0.66, `gap` 0.24) reproduce these." % (
                   len(lk), st.median(gp), q(gp, .25), q(gp, .75), st.median(th), q(th, .25), q(th, .75), st.median(tm)), ""]

    # craft drivers
    def rate(rs, cond):
        rs = [r for r in rs if r["l_craft"]]
        hit = [r for r in rs if cond(r)]
        return (round(100 * sum(r["l_craft"] in ("4", "5") for r in hit) / len(hit)) if hit else None, len(hit))
    drivers = [
        ("flat or cut style", lambda r: r["l_style"] in ("flat", "cut")), ("detailed or gradient style", lambda r: r["l_style"] == "detail"),
        ("simplicity 1 or 2", lambda r: r["l_simple"] in ("1", "2")), ("simplicity 4 or 5", lambda r: r["l_simple"] in ("4", "5")),
        ("abstract geometric", lambda r: r["l_kind"] == "G"), ("initial letterform", lambda r: r["l_kind"] == "LI"),
        ("pictorial object", lambda r: r["l_kind"] == "P"), ("character or animal", lambda r: r["l_kind"] == "C"),
        ("no container", lambda r: r["l_cont"] == "none"), ("circle container", lambda r: r["l_cont"] == "circle"),
        ("shield container", lambda r: r["l_cont"] == "shield"), ("badge (word in a shape)", lambda r: r["l_comp"] == "B"),
        ("1 or 2 colors", lambda r: r["source"] in ("gb", "svgl") and r["n_colors"] in ("1", "2")),
        ("4 or more colors", lambda r: r["source"] in ("gb", "svgl") and r["n_colors"] not in ("", "1", "2", "3")),
    ]
    wdrivers = [("tight tracking", lambda r: r["l_track"] == "tight"), ("wide tracking", lambda r: r["l_track"] == "wide"),
                ("lowercase", lambda r: r["l_case"] == "lower"), ("uppercase", lambda r: r["l_case"] == "upper"),
                ("neo grotesk", lambda r: r["l_type"] == "neo"), ("geometric sans", lambda r: r["l_type"] == "geo"),
                ("display lettering", lambda r: r["l_type"] == "display"), ("serif", lambda r: r["l_type"] == "serif"),
                ("medium or bold weight", lambda r: r["l_weight"] in ("medium", "bold")), ("light weight", lambda r: r["l_weight"] == "light"),
                ("one custom detail", lambda r: r["l_custom"] not in ("", "none")), ("no custom detail", lambda r: r["l_custom"] == "none")]
    base = rate(marks, lambda r: True)[0]
    md += ["## What separates strong logos", "", "Share of logos rated craft 4 or 5 when a trait is present. Baseline for symbols: %s%%." % base, "",
           "| symbol trait | craft 4+ rate | n |", "|---|---|---|"]
    md += ["| %s | %s%% | %d |" % (n, *rate(marks, f)) for n, f in drivers]
    wbase = rate(words, lambda r: True)[0]
    md += ["", "Baseline for wordmarks: %s%%." % wbase, "", "| wordmark trait | craft 4+ rate | n |", "|---|---|---|"]
    md += ["| %s | %s%% | %d |" % (n, *rate(words, f)) for n, f in wdrivers]
    md += ["", "These are associations in this sample, not proof that a trait causes quality.", ""]
    open(os.path.join(R, "patterns.md"), "w").write("\n".join(md))
    print("rows", len(rows), "brands", len(brands), "labeled", len(L), "marks", len(marks), "words", len(words))


if __name__ == "__main__":
    main()
